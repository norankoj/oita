function smInGroup(name, label) {
  const g = smGrp(name), r = smGrp(label);
  if (!g || !r || g.b != null || g.p !== r.p) return false;
  return g.a == null ? r.a == null : r.a != null && g.a >= r.a && g.a <= (r.b ?? r.a);
}
