function smGrp(s) {
  const m = /^(기혼|married|em|jm|오이타|oita|group)?0*(\d+)?(?:~0*(\d+))?(?:조|班)?$/.exec(String(s).toLowerCase().replace(/\s+/g, ''));
  if (!m || (!m[2] && m[1] !== 'jm')) return null;
  return { p: SM_GP[m[1] || ''], a: m[2] ? +m[2] : null, b: m[3] ? +m[3] : null };
}
